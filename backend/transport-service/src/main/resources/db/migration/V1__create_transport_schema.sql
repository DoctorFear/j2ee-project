CREATE TABLE stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    station_type VARCHAR(20) NOT NULL CHECK (station_type IN ('TERMINAL','OFFICE','ROAD_STOP','REST_STOP')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE station_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id BIGINT NOT NULL,
    address VARCHAR(255) NOT NULL,
    effective_from_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_station_address_station FOREIGN KEY (station_id) REFERENCES stations(id) ON DELETE CASCADE,
    CONSTRAINT uq_station_address_effective_from UNIQUE (station_id, effective_from_at)
);

CREATE TABLE routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    version_no INT NOT NULL DEFAULT 1,
    name VARCHAR(200) NOT NULL,
    base_price DECIMAL(15,0) NOT NULL,
    effective_from_at TIMESTAMP(6) NOT NULL,
    effective_to_at TIMESTAMP(6),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT uq_route_code_version UNIQUE (code, version_no),
    CONSTRAINT ck_route_version CHECK (version_no >= 1),
    CONSTRAINT ck_route_price CHECK (base_price >= 0),
    CONSTRAINT ck_route_period CHECK (effective_to_at IS NULL OR effective_to_at > effective_from_at)
);

CREATE TABLE station_segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_station_id BIGINT NOT NULL,
    to_station_id BIGINT NOT NULL,
    distance_km DECIMAL(10,2) NOT NULL,
    duration_minutes INT NOT NULL,
    CONSTRAINT fk_segment_origin FOREIGN KEY (from_station_id) REFERENCES stations(id),
    CONSTRAINT fk_segment_destination FOREIGN KEY (to_station_id) REFERENCES stations(id),
    CONSTRAINT uq_station_segment_direction UNIQUE (from_station_id, to_station_id),
    CONSTRAINT ck_segment_distinct_stations CHECK (from_station_id <> to_station_id),
    CONSTRAINT ck_segment_measurements CHECK (distance_km > 0 AND duration_minutes > 0)
);

CREATE TABLE route_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    station_id BIGINT NOT NULL,
    stop_order INT NOT NULL,
    distance_km DECIMAL(10,2) NOT NULL,
    offset_minutes INT NOT NULL,
    allow_pickup BOOLEAN NOT NULL DEFAULT FALSE,
    allow_dropoff BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_route_stop_route FOREIGN KEY (route_id) REFERENCES routes(id),
    CONSTRAINT fk_route_stop_station FOREIGN KEY (station_id) REFERENCES stations(id),
    CONSTRAINT uq_route_stop_order UNIQUE (route_id, stop_order),
    CONSTRAINT ck_stop_measurements CHECK (stop_order >= 1 AND distance_km >= 0 AND offset_minutes >= 0),
    CONSTRAINT ck_stop_origin CHECK (stop_order <> 1 OR (distance_km = 0 AND offset_minutes = 0))
);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_plate VARCHAR(20) NOT NULL,
    service_type VARCHAR(20) NOT NULL CHECK (service_type IN ('SEAT','BERTH','LIMOUSINE')),
    capacity INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','MAINTENANCE','INACTIVE')),
    CONSTRAINT uq_vehicle_license_plate UNIQUE (license_plate),
    CONSTRAINT ck_vehicle_capacity CHECK (capacity > 0)
);

CREATE TABLE drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    license_number VARCHAR(50),
    license_class VARCHAR(20),
    license_expiry_on DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL,
    route_id BIGINT NOT NULL,
    vehicle_id BIGINT,
    departure_at TIMESTAMP(6) NOT NULL,
    arrival_at TIMESTAMP(6) NOT NULL,
    published_at TIMESTAMP(6),
    estimated_departure_at TIMESTAMP(6),
    estimated_arrival_at TIMESTAMP(6),
    actual_departure_at TIMESTAMP(6),
    actual_arrival_at TIMESTAMP(6),
    cancelled_at TIMESTAMP(6),
    cancel_reason VARCHAR(255),
    ticket_price DECIMAL(15,0) NOT NULL,
    capacity_snapshot INT,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','SCHEDULED','RUNNING','COMPLETED','CANCELLED')),
    sale_status VARCHAR(20) NOT NULL DEFAULT 'NOT_OPEN' CHECK (sale_status IN ('NOT_OPEN','OPEN','PAUSED','CLOSED')),
    CONSTRAINT uq_trip_code UNIQUE (code),
    CONSTRAINT fk_trip_route FOREIGN KEY (route_id) REFERENCES routes(id),
    CONSTRAINT fk_trip_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id),
    CONSTRAINT ck_trip_schedule_price CHECK (arrival_at > departure_at AND ticket_price >= 0),
    CONSTRAINT ck_trip_vehicle_capacity CHECK (
        (vehicle_id IS NULL AND capacity_snapshot IS NULL)
        OR (vehicle_id IS NOT NULL AND capacity_snapshot IS NOT NULL AND capacity_snapshot > 0)),
    CONSTRAINT ck_trip_publication CHECK (
        status = 'CANCELLED' OR (status = 'DRAFT' AND published_at IS NULL)
        OR (status IN ('SCHEDULED','RUNNING','COMPLETED') AND published_at IS NOT NULL)),
    CONSTRAINT ck_trip_published_vehicle CHECK (published_at IS NULL OR vehicle_id IS NOT NULL),
    CONSTRAINT ck_trip_sale_state CHECK (
        (status = 'DRAFT' AND sale_status = 'NOT_OPEN') OR status = 'SCHEDULED'
        OR (status IN ('RUNNING','COMPLETED','CANCELLED') AND sale_status = 'CLOSED')),
    CONSTRAINT ck_trip_actual_times CHECK (
        (status IN ('DRAFT','SCHEDULED','CANCELLED') AND actual_departure_at IS NULL AND actual_arrival_at IS NULL)
        OR (status = 'RUNNING' AND actual_departure_at IS NOT NULL AND actual_arrival_at IS NULL)
        OR (status = 'COMPLETED' AND actual_departure_at IS NOT NULL AND actual_arrival_at IS NOT NULL
            AND actual_arrival_at > actual_departure_at)),
    CONSTRAINT ck_trip_departure_after_publication CHECK (
        actual_departure_at IS NULL OR (published_at IS NOT NULL AND actual_departure_at >= published_at)),
    CONSTRAINT ck_trip_estimated_times CHECK (
        estimated_departure_at IS NULL OR estimated_arrival_at IS NULL OR estimated_arrival_at > estimated_departure_at),
    CONSTRAINT ck_trip_cancellation CHECK (
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL AND cancel_reason IS NOT NULL
            AND CHAR_LENGTH(TRIM(cancel_reason)) > 0 AND (published_at IS NULL OR cancelled_at >= published_at))
        OR (status <> 'CANCELLED' AND cancelled_at IS NULL AND cancel_reason IS NULL))
);

CREATE TABLE trip_drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('PRIMARY','RELIEF')),
    CONSTRAINT fk_trip_driver_trip FOREIGN KEY (trip_id) REFERENCES trips(id),
    CONSTRAINT fk_trip_driver_driver FOREIGN KEY (driver_id) REFERENCES drivers(id),
    CONSTRAINT uq_trip_driver UNIQUE (trip_id, driver_id)
);

CREATE TABLE trip_statistics (
    trip_id BIGINT PRIMARY KEY,
    valid_ticket_count INT NOT NULL,
    collected_amount DECIMAL(15,0) NOT NULL,
    refunded_amount DECIMAL(15,0) NOT NULL,
    source_revision NUMERIC(20,0) NOT NULL,
    source_as_of_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_trip_statistics_trip FOREIGN KEY (trip_id) REFERENCES trips(id),
    CONSTRAINT ck_stats_nonnegative CHECK (valid_ticket_count >= 0 AND collected_amount >= 0 AND refunded_amount >= 0),
    CONSTRAINT ck_stats_revision CHECK (source_revision BETWEEN 1 AND 18446744073709551615)
);

CREATE INDEX idx_trips_route_departure ON trips(route_id, departure_at);
CREATE INDEX idx_trips_vehicle_departure ON trips(vehicle_id, departure_at);
CREATE UNIQUE INDEX uq_trip_one_primary ON trip_drivers(trip_id) WHERE role = 'PRIMARY';
CREATE INDEX idx_trip_driver_assignments ON trip_drivers(driver_id, trip_id);
