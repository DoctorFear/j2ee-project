-- Databases previously managed by Hibernate start at Flyway baseline version 1.
-- A database created by V1 already has the new schema.
DO $transport_upgrade$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'stations' AND column_name = 'address'
    ) THEN
        RETURN;
    END IF;

    ALTER TABLE stations RENAME COLUMN type TO station_type;
    ALTER TABLE stations ALTER COLUMN name TYPE VARCHAR(150), ALTER COLUMN status SET DEFAULT 'ACTIVE';

    CREATE TABLE station_addresses (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        station_id BIGINT NOT NULL,
        address VARCHAR(255) NOT NULL,
        effective_from_at TIMESTAMP(6) NOT NULL,
        CONSTRAINT fk_station_address_station FOREIGN KEY (station_id) REFERENCES stations(id) ON DELETE CASCADE,
        CONSTRAINT uq_station_address_effective_from UNIQUE (station_id, effective_from_at)
    );

    INSERT INTO station_addresses(station_id, address, effective_from_at)
    SELECT id, address, TIMESTAMP '1970-01-01 00:00:00' FROM stations;
    ALTER TABLE stations DROP COLUMN address;

    CREATE TABLE station_segments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        from_station_id BIGINT NOT NULL,
        to_station_id BIGINT NOT NULL,
        distance_km DECIMAL(10,2) NOT NULL,
        duration_minutes INT NOT NULL,
        CONSTRAINT fk_segment_origin FOREIGN KEY (from_station_id) REFERENCES stations(id),
        CONSTRAINT fk_segment_destination FOREIGN KEY (to_station_id) REFERENCES stations(id),
        CONSTRAINT uq_station_segment_direction UNIQUE (from_station_id, to_station_id),
        CONSTRAINT ck_segment_distinct_stations CHECK (from_station_id <> to_station_id),
        CONSTRAINT ck_segment_measurements CHECK (distance_km > 0 AND duration_minutes > 0)
    );

    ALTER TABLE routes
        ALTER COLUMN code TYPE VARCHAR(30),
        ALTER COLUMN name TYPE VARCHAR(200),
        ALTER COLUMN version_no SET DEFAULT 1,
        ALTER COLUMN status SET DEFAULT 'ACTIVE',
        ADD CONSTRAINT ck_route_version CHECK (version_no >= 1),
        ADD CONSTRAINT ck_route_price CHECK (base_price >= 0),
        ADD CONSTRAINT ck_route_period CHECK (effective_to_at IS NULL OR effective_to_at > effective_from_at);

    ALTER TABLE route_stops RENAME COLUMN allow_drop_off TO allow_dropoff;
    IF EXISTS (SELECT 1 FROM route_stops WHERE stop_order < 0) THEN
        RAISE EXCEPTION 'Negative legacy stop order requires correction before migration';
    END IF;
    UPDATE route_stops SET stop_order = -stop_order - 1
        WHERE route_id IN (SELECT route_id FROM route_stops WHERE stop_order = 0);
    UPDATE route_stops SET stop_order = -stop_order WHERE stop_order < 0;
    ALTER TABLE route_stops
        ALTER COLUMN allow_pickup SET DEFAULT FALSE,
        ALTER COLUMN allow_dropoff SET DEFAULT FALSE,
        ADD CONSTRAINT ck_stop_measurements CHECK (stop_order >= 1 AND distance_km >= 0 AND offset_minutes >= 0),
        ADD CONSTRAINT ck_stop_origin CHECK (stop_order <> 1 OR (distance_km = 0 AND offset_minutes = 0));

    ALTER TABLE vehicles RENAME COLUMN type TO service_type;
    ALTER TABLE vehicles
        ALTER COLUMN license_plate TYPE VARCHAR(20),
        ALTER COLUMN status SET DEFAULT 'ACTIVE',
        ADD CONSTRAINT uq_vehicle_license_plate UNIQUE (license_plate),
        ADD CONSTRAINT ck_vehicle_capacity CHECK (capacity > 0);

    ALTER TABLE drivers
        ALTER COLUMN full_name TYPE VARCHAR(150),
        ALTER COLUMN phone TYPE VARCHAR(20),
        ALTER COLUMN license_number TYPE VARCHAR(50),
        ALTER COLUMN license_class TYPE VARCHAR(20),
        ALTER COLUMN license_expiry_on TYPE DATE USING license_expiry_on::DATE,
        ALTER COLUMN status SET DEFAULT 'ACTIVE';

    ALTER TABLE trips
        ALTER COLUMN code TYPE VARCHAR(60),
        ALTER COLUMN vehicle_id DROP NOT NULL,
        ALTER COLUMN capacity_snapshot DROP NOT NULL,
        ALTER COLUMN status SET DEFAULT 'DRAFT',
        ALTER COLUMN sale_status SET DEFAULT 'NOT_OPEN',
        ADD COLUMN published_at TIMESTAMP(6),
        ADD COLUMN cancelled_at TIMESTAMP(6),
        ADD COLUMN cancel_reason VARCHAR(255);

    UPDATE trips
    SET published_at = LEAST(COALESCE(actual_departure_at, departure_at), CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    WHERE status IN ('SCHEDULED','RUNNING','COMPLETED');
    UPDATE trips SET sale_status = 'CLOSED' WHERE status IN ('RUNNING','COMPLETED','CANCELLED');
    UPDATE trips SET sale_status = 'NOT_OPEN' WHERE status = 'DRAFT';
    UPDATE trips
    SET cancelled_at = CURRENT_TIMESTAMP AT TIME ZONE 'UTC', cancel_reason = 'Lý do hủy không có trong dữ liệu cũ'
    WHERE status = 'CANCELLED';

    ALTER TABLE trips
        ADD CONSTRAINT uq_trip_code UNIQUE (code),
        ADD CONSTRAINT ck_trip_schedule_price CHECK (arrival_at > departure_at AND ticket_price >= 0),
        ADD CONSTRAINT ck_trip_vehicle_capacity CHECK (
            (vehicle_id IS NULL AND capacity_snapshot IS NULL)
            OR (vehicle_id IS NOT NULL AND capacity_snapshot IS NOT NULL AND capacity_snapshot > 0)),
        ADD CONSTRAINT ck_trip_publication CHECK (
            status = 'CANCELLED' OR (status = 'DRAFT' AND published_at IS NULL)
            OR (status IN ('SCHEDULED','RUNNING','COMPLETED') AND published_at IS NOT NULL)),
        ADD CONSTRAINT ck_trip_published_vehicle CHECK (published_at IS NULL OR vehicle_id IS NOT NULL),
        ADD CONSTRAINT ck_trip_sale_state CHECK (
            (status = 'DRAFT' AND sale_status = 'NOT_OPEN') OR status = 'SCHEDULED'
            OR (status IN ('RUNNING','COMPLETED','CANCELLED') AND sale_status = 'CLOSED')),
        ADD CONSTRAINT ck_trip_actual_times CHECK (
            (status IN ('DRAFT','SCHEDULED','CANCELLED') AND actual_departure_at IS NULL AND actual_arrival_at IS NULL)
            OR (status = 'RUNNING' AND actual_departure_at IS NOT NULL AND actual_arrival_at IS NULL)
            OR (status = 'COMPLETED' AND actual_departure_at IS NOT NULL AND actual_arrival_at IS NOT NULL
                AND actual_arrival_at > actual_departure_at)),
        ADD CONSTRAINT ck_trip_departure_after_publication CHECK (
            actual_departure_at IS NULL OR (published_at IS NOT NULL AND actual_departure_at >= published_at)),
        ADD CONSTRAINT ck_trip_estimated_times CHECK (
            estimated_departure_at IS NULL OR estimated_arrival_at IS NULL OR estimated_arrival_at > estimated_departure_at),
        ADD CONSTRAINT ck_trip_cancellation CHECK (
            (status = 'CANCELLED' AND cancelled_at IS NOT NULL AND cancel_reason IS NOT NULL
                AND CHAR_LENGTH(TRIM(cancel_reason)) > 0 AND (published_at IS NULL OR cancelled_at >= published_at))
            OR (status <> 'CANCELLED' AND cancelled_at IS NULL AND cancel_reason IS NULL));

    CREATE INDEX idx_trips_route_departure ON trips(route_id, departure_at);
    CREATE INDEX idx_trips_vehicle_departure ON trips(vehicle_id, departure_at);
    CREATE UNIQUE INDEX uq_trip_one_primary ON trip_drivers(trip_id) WHERE role = 'PRIMARY';
    CREATE INDEX idx_trip_driver_assignments ON trip_drivers(driver_id, trip_id);

    ALTER TABLE trip_statistic RENAME TO trip_statistics;
    ALTER TABLE trip_statistics
        ADD COLUMN source_revision NUMERIC(20,0),
        ADD COLUMN source_as_of_at TIMESTAMP(6);
    UPDATE trip_statistics
    SET updated_at = COALESCE(updated_at, CURRENT_TIMESTAMP AT TIME ZONE 'UTC');
    UPDATE trip_statistics SET source_revision = 1, source_as_of_at = updated_at;
    ALTER TABLE trip_statistics
        ALTER COLUMN updated_at SET NOT NULL,
        ALTER COLUMN source_revision SET NOT NULL,
        ALTER COLUMN source_as_of_at SET NOT NULL,
        ADD CONSTRAINT ck_stats_nonnegative CHECK (valid_ticket_count >= 0 AND collected_amount >= 0 AND refunded_amount >= 0),
        ADD CONSTRAINT ck_stats_revision CHECK (source_revision BETWEEN 1 AND 18446744073709551615);
END;
$transport_upgrade$;
